-- Dumping structure for procedure pd_fix.prosedur_rekap_bulanan
DELIMITER //
CREATE PROCEDURE `prosedur_rekap_bulanan`()
BEGIN
    DECLARE bulan_ini INT;
    DECLARE tanggal_hari_ini DATE;
    DECLARE jam_tersibuk INT;

    SET bulan_ini = MONTH(NOW());
    SET tanggal_hari_ini = CURDATE();

    -- Ambil jam tersibuk dalam bulan ini
    SELECT HOUR(waktu_penyebrangan)
    INTO jam_tersibuk
    FROM data_terkini
    WHERE MONTH(waktu_penyebrangan) = bulan_ini
    GROUP BY HOUR(waktu_penyebrangan)
    ORDER BY SUM(jumlah_penyebrang) DESC
    LIMIT 1;

    INSERT INTO rekap_bulanan (bulan, tanggal, total_crossing, rata_rata_durasi, jam_tersibuk)
    SELECT
        bulan_ini,
        tanggal_hari_ini,
        SUM(jumlah_penyebrang),
        AVG(durasi_penyebrangan),
        jam_tersibuk
    FROM data_terkini
    WHERE MONTH(waktu_penyebrangan) = bulan_ini;
END//
DELIMITER ;

-- Dumping structure for procedure pd_fix.prosedur_rekap_harian
DELIMITER //
CREATE PROCEDURE `prosedur_rekap_harian`()
BEGIN
    DECLARE jam_sekarang INT;
    SET jam_sekarang = HOUR(NOW());

    INSERT INTO rekap_harian (tanggal, jam, total_crossing, rata_rata_durasi, jam_tersibuk)
    SELECT
        CURDATE(),
        jam_sekarang,
        SUM(jumlah_penyebrang),
        AVG(durasi_penyebrangan),
        CASE 
            WHEN SUM(jumlah_penyebrang) > 100 OR AVG(durasi_penyebrangan) > 1000 THEN 'YA'
            ELSE 'TIDAK'
        END
    FROM data_terkini
    WHERE HOUR(waktu_penyebrangan) = jam_sekarang AND DATE(waktu_penyebrangan) = CURDATE();
END//
DELIMITER ;

-- Dumping structure for procedure pd_fix.prosedur_rekap_jam
DELIMITER //
CREATE PROCEDURE `prosedur_rekap_jam`()
BEGIN
    DECLARE waktu_awal DATETIME;
    DECLARE waktu_akhir DATETIME;

    SET waktu_akhir = NOW();
    SET waktu_awal = DATE_SUB(waktu_akhir, INTERVAL 10 MINUTE);

    INSERT INTO rekap_jam (waktu, total_crossing, rata_rata_durasi)
    SELECT
        NOW(),
        SUM(jumlah_penyebrang),
        AVG(durasi_penyebrangan)
    FROM data_terkini
    WHERE waktu_penyebrangan BETWEEN waktu_awal AND waktu_akhir;
END//
DELIMITER ;

-- Dumping structure for procedure pd_fix.prosedur_rekap_mingguan
DELIMITER //
CREATE PROCEDURE `prosedur_rekap_mingguan`()
BEGIN
    DECLARE tanggal_hari_ini DATE;
    DECLARE nama_hari VARCHAR(10);
    DECLARE jam_tersibuk INT;

    SET tanggal_hari_ini = CURDATE();
    SET nama_hari = DAYNAME(tanggal_hari_ini);

    -- Ambil jam tersibuk berdasarkan jumlah penyebrang terbanyak hari ini
    SELECT HOUR(waktu_penyebrangan)
    INTO jam_tersibuk
    FROM data_terkini
    WHERE DATE(waktu_penyebrangan) = tanggal_hari_ini
    GROUP BY HOUR(waktu_penyebrangan)
    ORDER BY SUM(jumlah_penyebrang) DESC
    LIMIT 1;

    INSERT INTO rekap_mingguan (tanggal, hari, total_crossing, rata_rata_durasi, jam_tersibuk)
    SELECT
        tanggal_hari_ini,
        nama_hari,
        SUM(jumlah_penyebrang),
        AVG(durasi_penyebrangan),
        jam_tersibuk
    FROM data_terkini
    WHERE DATE(waktu_penyebrangan) = tanggal_hari_ini;
END//
DELIMITER ;

